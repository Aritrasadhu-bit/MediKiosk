/**
 * Hindi gloss of a clinical term, for inline reading on the patient screen.
 * Kept deliberately small: translating every clinical term mechanically produces
 * worse comprehension than a clear English term plus a Hindi frame, so only
 * high-frequency, high-risk items are glossed.
 */
const HI_TERMS: Array<[RegExp, string]> = [
  [/chest pain/i, "सीने में दर्द"],
  [/breathless|dyspno?ea/i, "साँस फूलना"],
  [/fever/i, "बुखार"],
  [/cough/i, "खाँसी"],
  [/headache/i, "सिरदर्द"],
  [/abdominal pain|stomach pain/i, "पेट में दर्द"],
  [/diabet/i, "मधुमेह (डायबिटीज)"],
  [/hypertens|blood pressure/i, "उच्च रक्तचाप"],
  [/anaemi|anemi/i, "एनीमिया (कम खून)"],
  [/asthma/i, "दमा"],
  [/tb|tuberculosis/i, "क्षय रोग"],
  [/medication|tablet/i, "दवाई"],
];

export function glossClinicalTerm(text: string, lang?: string | null): string {
  if (lang !== "hi") return text;
  for (const [re, hi] of HI_TERMS) {
    if (re.test(text)) return hi;
  }
  return text;
}

