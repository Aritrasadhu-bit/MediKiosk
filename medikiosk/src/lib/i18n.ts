/** Translate a queue-board key for a board language code, falling back to English. */
export function qt(key: string, lang?: string | null): string {
  const dict = QUEUE_TEXT[lang ?? ""];
  const val = dict?.[key];
  if (val) return val;
  return QUEUE_TEXT.en[key] ?? key;
}

